import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { strFromU8, unzipSync } from 'fflate';
import { preview } from 'vite';

const [executablePath, tripo = 'D:/downloads/Tripo'] = process.argv.slice(2);
const { chromium } = await import('../test-results/e00-browser/node_modules/playwright-core/index.mjs');
const dir = resolve('test-results/e11'), fixtures = resolve('tools/e00/fixtures');
const known = ['idle', 'walk', 'run', 'jump', 'squat', 'sit', 'wave', 'punch', 'reach', 'twist'];
const server = await preview({ preview: { host: '127.0.0.1', port: 4296 } });
const url = `http://127.0.0.1:${server.httpServer.address().port}/`;
const outside = [], errors = [], bindings = [];
let browser;
try {
  browser = await chromium.launch({ ...(executablePath ? { executablePath } : { channel: 'chrome' }),
    args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
  const context = await browser.newContext({ viewport: { width: 1550, height: 1620 } });
  await context.route(/^https?:/, route => {
    const requested = route.request().url();
    if (requested.startsWith(url)) return route.continue();
    outside.push(requested);
    return route.abort();
  });
  const page = await context.newPage();
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (/PropertyBinding: (No target|Trying to update)/.test(message.text())) bindings.push(message.text()); });
  page.on('dialog', dialog => dialog.accept());
  await page.goto(url);
  const field = id => page.locator(`#${id}`);
  const click = id => field(id).click();
  const text = id => field(id).textContent();
  const choose = (id, value) => field(id).selectOption(value);
  const fill = (id, value) => field(id).fill(String(value));
  const ready = () => page.waitForFunction(() => !document.querySelector('#sources').disabled, null, { timeout: 120000 });
  const status = async pattern => assert.match(await text('status'), pattern, await text('diag-info'));
  const run = async (id, pattern) => { await click(id); await ready(); await status(pattern); };
  const open = async (path, pattern) => { await field('sources').setInputFiles(path); await ready(); await status(pattern); };
  const enter = async () => { if (await field('diag-tools').isHidden()) await click('diag-mode'); };
  async function details(id) {
    if (await field(id).getAttribute('open') === null) await field(id).locator('summary').click();
  }
  async function option(id, label) {
    const rows = await field(id).locator('option').evaluateAll(items => items.map(item => ({ name: item.text.trim().split(' · ')[0], value: item.value })));
    const found = rows.find(item => item.name === label);
    assert.ok(found, `Missing ${label} in ${id} (${rows.map(item => item.name).join(', ')})`);
    return found.value;
  }
  const scrub = value => field('diag-scrub').evaluate((input, time) => {
    input.value = String(time);
    input.dispatchEvent(new Event('input', { bubbles: true }));
  }, value);
  const duration = async () => Number(await field('diag-scrub').getAttribute('max'));
  const timeline = async () => parseFloat(await text('diag-time'));
  const viewport = field('viewport');
  async function download(id, name) {
    const [result] = await Promise.all([page.waitForEvent('download', { timeout: 120000 }), click(id)]);
    const path = join(dir, name);
    await result.saveAs(path);
    await ready();
    return readFile(path);
  }
  const manifest = bytes => JSON.parse(strFromU8(unzipSync(bytes)['manifest.json']));
  async function publish(name) {
    await details('diag-export');
    if (name) await fill('diag-publish-name', name);
    await run('diag-publish', /Publish diagnostic clip applied/);
  }

  await open(join(fixtures, 'shared_skin.fbx'), /3 bones/);
  await enter();
  await details('diag-mapping');
  await run('diag-suggest', /Apply suggested humanoid roles applied/);
  assert.match(await text('diag-map-summary'), /Partial check · 2 of 10/);
  assert.match(await text('diag-roles'), /Missing/);
  await choose('diag-clip', 'idle');
  assert.match(await text('diag-info'), /Idle · partial/);
  assert.equal(await field('diag-clip').locator('option[value="squat"]').isDisabled(), true);

  const tripoSource = join(tripo, 'man character 3d model.glb');
  await open(tripoSource, /67 bones/);
  await enter();
  await details('diag-mapping');
  await run('diag-suggest', /Apply suggested humanoid roles applied/);
  assert.match(await text('diag-map-summary'), /Complete humanoid · 10 of 10/);
  const left = await option('diag-map-leftUpperArm', 'Left_UpperArm');
  const right = await option('diag-map-rightUpperArm', 'Right_UpperArm');
  const hips = await option('diag-map-hips', 'Hips');
  await choose('diag-map-leftUpperArm', right);
  await ready();
  assert.match(await text('diag-roles'), /Duplicate joint/);
  assert.match(await text('diag-map-summary'), /Partial check/);
  await choose('diag-map-leftUpperArm', left);
  await ready();
  assert.match(await text('diag-map-summary'), /Complete humanoid/);
  await details('diag-calibration');
  await choose('diag-reference', 'A');
  await run('diag-calibrate', /Save A-pose calibration applied/);
  assert.match(await text('diag-calibration-state'), /A-pose reference is active/);
  await choose('diag-axis-role', 'leftUpperArm');
  await fill('diag-axis-z', '5');
  await run('diag-save-axes', /Calibrate anatomical axes applied/);
  await fill('diag-arm-offset', '16');
  await fill('diag-leg-offset', '9');
  await fill('diag-hip-y', '.035');
  await run('diag-save-offsets', /Save character offsets applied/);

  const available = await field('diag-clip').locator('option[data-kind="built-in"]').evaluateAll(nodes => nodes.map(node => [node.value, node.disabled]));
  assert.deepEqual(available, known.map(id => [id, false]));
  const baseline = await download('export', 'tripo-rest.glb');
  for (const id of known) {
    await choose('diag-clip', id);
    assert.ok(await duration() > .6);
    await scrub(await duration() * .5);
    assert.ok(await timeline() > .3);
  }
  await choose('diag-clip', 'squat');
  await scrub(1.3);
  assert.match(await text('diag-info'), /Squat.*Character offsets active/);
  const corrected = await viewport.screenshot();
  await writeFile(join(dir, 'tripo-squat.png'), corrected);
  await field('diag-corrected').uncheck();
  assert.notDeepEqual(corrected, await viewport.screenshot());
  await field('diag-corrected').check();
  await field('diag-compare').check();
  assert.notDeepEqual(corrected, await viewport.screenshot());
  await field('diag-compare').uncheck();
  await choose('diag-display', 'unlit');
  const flat = await viewport.screenshot();
  await choose('diag-display', 'heatmap');
  assert.notDeepEqual(flat, await viewport.screenshot());
  await choose('diag-display', 'lit');
  assert.deepEqual(await download('export', 'tripo-preview.glb'), baseline);
  await fill('diag-pose-name', 'Squat checkpoint');
  await run('diag-save-pose', /Save diagnostic pose applied/);
  await publish('Diagnostic_Squat_Corrected');
  await choose('diag-clip', 'walk');
  await scrub(await duration() * .75);
  assert.match(await text('diag-info'), /In-place/);
  const inplace = await viewport.screenshot();
  await writeFile(join(dir, 'tripo-walk.png'), inplace);
  await field('diag-root').check();
  assert.match(await text('diag-info'), /Root motion/);
  assert.notDeepEqual(inplace, await viewport.screenshot());
  await publish('Diagnostic_Walk_Travel');
  const saved = manifest(await download('save-project', 'tripo-humanoid.assetfixer'));
  assert.equal(saved.schemaVersion, 11);
  assert.equal(saved.working.humanoid.profile.mapping.leftUpperArm, left);
  assert.deepEqual(saved.working.humanoid.profile.axes.leftUpperArm, [0, 0, 5]);
  assert.equal(saved.working.humanoid.profile.corrections.pelvis[1], .035);
  const pose = saved.working.poses.saved[0];
  assert.equal(pose.name, 'Squat checkpoint');
  assert.ok(Math.hypot(...pose.translations[hips]) > .1);
  await download('export', 'tripo-published.glb');
  await open(join(dir, 'tripo-humanoid.assetfixer'), /Project restored/);
  await enter();
  await details('diag-calibration');
  assert.match(await text('diag-calibration-state'), /A-pose reference is active/);
  await choose('diag-preset', await option('diag-preset', 'Squat checkpoint'));
  assert.match(await text('diag-info'), /Squat checkpoint/);
  await click('rig-mode');
  await choose('rig-edit-mode', 'pose');
  await choose('rig-saved', await option('rig-saved', 'Squat checkpoint'));
  await ready();
  const manual = manifest(await download('save-project', 'tripo-saved-manual.assetfixer'));
  assert.deepEqual(manual.working.poses.translations, pose.translations);
  await run('rig-reset-pose', /Reset manual pose applied/);

  await open(join(dir, 'humanoid.fbx'), /544 triangles.*25 bones.*1 clips/);
  await enter();
  await details('diag-mapping');
  await run('diag-suggest', /Apply suggested humanoid roles applied/);
  assert.match(await text('diag-map-summary'), /10 of 10/);
  await details('diag-calibration');
  await choose('diag-reference', 'T');
  await run('diag-calibrate', /Save T-pose calibration applied/);
  await choose('diag-clip', await option('diag-clip', 'SourceStep'));
  await scrub(.75);
  assert.match(await text('diag-info'), /In-place/);
  await field('diag-root').check();
  assert.match(await text('diag-info'), /Root motion/);
  await choose('diag-clip', 'squat');
  await scrub(1.3);
  await fill('diag-pose-name', 'FBX squat reference');
  await run('diag-save-pose', /Save diagnostic pose applied/);
  await click('rig-mode');
  await choose('rig-edit-mode', 'pose');
  await choose('rig-saved', await option('rig-saved', 'FBX squat reference'));
  await ready();
  await details('rig-clips');
  await field('rig-include-offsets').check();
  await run('rig-adapt', /Save adapted clip applied/);
  const adapted = manifest(await download('save-project', 'humanoid-adapted.assetfixer'));
  assert.deepEqual(adapted.working.rig.clips[0].translationOffsets, adapted.working.poses.saved[0].translations);
  assert.ok(Object.values(adapted.working.rig.clips[0].translationOffsets).some(offset => Math.hypot(...offset) > .1));
  await enter();
  await choose('diag-clip', await option('diag-clip', 'SourceStep_Adapted_1'));
  await scrub(.5);
  assert.equal(await field('diag-compare').isEnabled(), true);
  await field('diag-compare').check();
  await field('diag-compare').uncheck();
  await click('rig-mode');
  await details('rig-clips');
  await run('rig-use-original', /Set clip export mode applied/);
  await run('rig-reset-pose', /Reset manual pose applied/);
  await enter();
  await details('diag-calibration');
  await fill('diag-arm-offset', '12');
  await fill('diag-leg-offset', '7');
  await fill('diag-hip-y', '.035');
  await run('diag-save-offsets', /Save character offsets applied/);
  await choose('diag-clip', 'squat');
  await scrub(1.25);
  await fill('diag-in', '.9');
  await fill('diag-out', '1.45');
  await field('diag-range').check();
  const frame = await timeline();
  await click('diag-step-forward');
  assert.ok(Math.abs(await timeline() - frame - 1 / 30) < .0011);
  await choose('diag-speed', 'custom');
  await fill('diag-speed-custom', '1.5');
  await click('diag-play');
  await page.waitForFunction(() => parseFloat(document.querySelector('#diag-time').textContent) < 1.2);
  await click('diag-play');
  assert.equal(await field('diag-play').getAttribute('aria-pressed'), 'false');
  await scrub(1.2);
  await download('export', 'humanoid-before-weights.zip');
  await run('diag-freeze', /Weight Paint froze Squat at 1\.200 s/);
  assert.equal(await field('weights-pose').inputValue(), 'diagnostic');
  assert.equal(await field('weights-time').inputValue(), '1.2');
  const hip = await option('weights-joint', 'Hips');
  const spine = await option('weights-joint', 'Spine');
  await choose('weights-joint', hip);
  await details('weights-limit-tools');
  await choose('weights-fallback', spine);
  await choose('weights-brush', 'replace');
  await fill('weights-value', '.7');
  await fill('weights-strength', '100');
  await fill('weights-hardness', '100');
  await fill('weights-radius', '512');
  await fill('weights-faces', 'F0');
  await field('weights-xray').check();
  await viewport.click();
  await ready();
  await status(/Replace weight stroke applied/);
  await enter();
  assert.equal(await field('diag-clip').inputValue(), 'squat');
  assert.equal(Number(await field('diag-in').inputValue()), .9);
  assert.equal(Number(await field('diag-out').inputValue()), 1.45);
  assert.equal(await field('diag-range').isChecked(), true);
  assert.equal(await timeline(), 1.2);
  for (const id of known) {
    await choose('diag-clip', id);
    if (id === 'walk') await field('diag-root').check();
    if (id === 'run' && await field('diag-root').isChecked()) await field('diag-root').uncheck();
    await publish(`Diagnostic_${id}`);
  }
  await choose('diag-clip', 'squat');
  await scrub(1.3);
  const fbx = manifest(await download('export', 'humanoid-published.zip'));
  assert.equal(fbx.meshes.clips, 11);
  await click('rig-mode');
  await choose('rig-edit-mode', 'rest');
  await choose('rig-joint', await option('rig-joint', 'Spine'));
  await choose('rig-operation', 'move');
  await choose('rig-space', 'world');
  await fill('rig-x', '.015');
  await run('rig-apply', /Move joint and rebind applied/);
  await details('rig-clips');
  await run('rig-exclude', /Set clip export mode applied/);
  await enter();
  assert.match(await text('diag-calibration-state'), /Recalibrate/);
  await run('export', /Published clip .* is stale/);

  assert.deepEqual(outside, []);
  assert.deepEqual(errors, []);
  assert.deepEqual(bindings, []);
  const report = { tripoClips: known, fbxClips: fbx.meshes.clips, partialRigClips: 2, duplicateDetection: true,
    calibratedAxes: true, rootMotion: true, correctedOverlay: true, importedComparison: true, translatedAdaptation: true, paintAndReplay: true,
    savedSquatTranslation: pose.translations[hips], previewExportIdentical: true, stalePublicationGuard: true, externalRequests: outside.length };
  await writeFile(join(dir, 'browser.json'), JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report));
} finally {
  await browser?.close();
  await new Promise(resolveClose => server.httpServer.close(resolveClose));
}
