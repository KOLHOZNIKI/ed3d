import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { strFromU8, unzipSync } from 'fflate';
import { preview } from 'vite';

const [executablePath] = process.argv.slice(2);
const { chromium } = await import('../test-results/e00-browser/node_modules/playwright-core/index.mjs');
const dir = resolve('test-results/e05');
const corpus = resolve('tools/e00/fixtures/corpus');
const server = await preview({ preview: { host: '127.0.0.1', port: 4288 } });
const url = `http://127.0.0.1:${server.httpServer.address().port}/`;
const errors = [], external = [];
let browser;
try {
  browser = await chromium.launch({ ...(executablePath ? { executablePath } : { channel: 'chrome' }),
    args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
  const context = await browser.newContext({ viewport: { width: 1500, height: 1450 } });
  await context.route(/^https?:/, route => {
    if (route.request().url().startsWith(url)) return route.continue();
    external.push(route.request().url());
    return route.abort();
  });
  const page = await context.newPage();
  page.on('dialog', dialog => dialog.accept());
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(url);
  const field = id => page.locator(`#${id}`);
  const click = id => field(id).click();
  const text = id => field(id).textContent();
  const select = (id, value) => field(id).selectOption(value);
  const ready = () => page.waitForFunction(() => !document.querySelector('#sources').disabled);
  const row = id => page.locator(`tr[data-contour="${id}"]`);
  const contours = () => page.locator('#repair-contours tr').evaluateAll(rows => rows.map(row => row.dataset.contour));
  const open = async (path, expected) => {
    await field('sources').setInputFiles(path);
    await ready();
    const status = await text('status');
    assert.ok(status.includes(expected), `${path}: expected ${expected}, got ${status}`);
  };
  const enter = async (label) => {
    await select('object-selection', label ? { label } : { index: 1 });
    if (await field('repair-tools').isHidden()) await click('repair-mode');
  };
  const apply = async () => { await click('repair-apply'); await ready(); assert.match(await text('status'), /Fill boundar.* applied/); };
  const undo = async () => { await click('undo-stroke'); await ready(); };
  const redo = async () => { await click('redo'); await ready(); };
  const download = async (id, name) => {
    const [file] = await Promise.all([page.waitForEvent('download'), click(id)]);
    const path = join(dir, name);
    await file.saveAs(path);
    await ready();
    return readFile(path);
  };
  const bundle = async name => {
    const zip = unzipSync(await download('export', name));
    return { zip, manifest: JSON.parse(strFromU8(zip['manifest.json'])) };
  };
  const report = async expected => assert.match(await text('repair-info'), expected);
  const toggleKeep = async id => { await click(`keep-${id}`); await ready(); };

  await open(join(corpus, 'f04_bottle.glb'), '104 triangles');
  await enter('Bottle');
  assert.deepEqual(await contours(), ['B12', 'B20', 'B48']);
  assert.equal(await field('keep-B48').getAttribute('aria-pressed'), 'true');
  await field('repair-auto-settings').locator('summary').click();
  await select('repair-scope', 'object');
  await field('repair-max-edges').fill('30');
  await field('repair-max-diameter').fill('0.01');
  await click('repair-auto');
  await report(/0 to fill · 3 skipped/);
  assert.match(await row('B12').textContent(), /Above the diameter limit/);
  await field('repair-max-diameter').fill('0');
  await select('repair-scope', 'selection');
  await field('pick-B12').check();
  await click('repair-auto');
  await report(/1 to fill · 2 skipped/);
  assert.match(await row('B20').textContent(), /Outside the selection/);
  await click('repair-cancel');
  await select('repair-scope', 'object');
  await toggleKeep('B12');
  await click('repair-auto');
  await report(/1 to fill · 2 skipped/);
  const before = await text('project-status');
  await page.keyboard.press('Escape');
  assert.equal(await text('project-status'), before);
  assert.deepEqual(await contours(), ['B12', 'B20', 'B48']);
  await download('save-project', 'protected.assetfixer');
  await open(join(dir, 'protected.assetfixer'), 'Project restored');
  await enter('Bottle');
  assert.equal(await field('keep-B12').getAttribute('aria-pressed'), 'true');
  await toggleKeep('B12');
  await click('repair-auto');
  await report(/2 to fill · 1 skipped/);
  assert.match(await row('B48').textContent(), /Keep Open/);
  await apply();
  assert.deepEqual(await contours(), ['B48']);
  await undo();
  assert.deepEqual(await contours(), ['B12', 'B20', 'B48']);
  await redo();
  assert.deepEqual(await contours(), ['B48']);
  const repairedGlb = await download('export', 'bottle-repaired.glb');
  assert.ok(repairedGlb.length);
  await open(join(dir, 'bottle-repaired.glb'), '106 triangles');
  await enter('Bottle');
  assert.deepEqual(await contours(), ['B48']);
  assert.equal(await field('keep-B48').getAttribute('aria-pressed'), 'true');

  await open(join(corpus, 'f03_boundaries.glb'), '80 triangles');
  await enter('ConcavePlanar');
  assert.deepEqual(await contours(), ['B8']);
  await field('pick-B8').check();
  await click('repair-manual');
  assert.equal(await field('mesh-operation').inputValue(), 'create');
  assert.match(await text('mesh-info'), /Preview/);
  await click('mesh-cancel');
  await enter('ConcavePlanar');
  await field('pick-B8').check();
  await select('repair-method', 'planar');
  await click('repair-preview');
  await report(/1 to fill · 0 skipped/);
  await apply();
  assert.deepEqual(await contours(), []);
  await enter('NonPlanar');
  await field('pick-B8').check();
  await click('repair-preview');
  assert.match(await row('B8').textContent(), /Deviation.*try Fan Fill/);
  assert.ok(await field('repair-apply').isDisabled());
  await select('repair-method', 'fan');
  await field('repair-custom').check();
  const originalX = await field('repair-x').inputValue();
  await field('repair-x').fill('10');
  await click('repair-preview');
  assert.match(await row('B8').textContent(), /Fan center must see every boundary edge/);
  await field('repair-x').fill(String(Number(originalX) + .01));
  await click('repair-preview');
  await report(/1 to fill · 0 skipped/);
  await apply();
  await download('export', 'contours-repaired.glb');
  await click('repair-select-new');
  assert.equal((await field('mesh-ids').inputValue()).split(', ').length, 8);

  await open(resolve('tools/e00/fixtures/topology_seams.zip'), '13 triangles');
  await enter();
  assert.deepEqual(await contours(), ['B8']);
  await field('pick-B8').check();
  await select('repair-method', 'planar');
  await click('repair-preview');
  assert.match(await row('B8').textContent(), /intersects existing face/);
  assert.ok(await field('repair-apply').isDisabled());
  await open(join(corpus, 'f16_non_manifold.glb'), 'Non-manifold topology');
  await enter();
  assert.match(await text('repair-contours'), /non-manifold|branch/);
  await select('repair-scope', 'object');
  await click('repair-auto');
  await report(/0 to fill/);

  await open(join(dir, 'bottle.zip'), '104 triangles');
  await enter('Bottle');
  assert.deepEqual(await contours(), ['B12', 'B20', 'B48']);
  await toggleKeep('B48');
  await field('repair-project').check();
  await click('repair-auto');
  await report(/2 to fill · 1 skipped/);
  await field('viewport').screenshot({ path: join(dir, 'bottle-preview.png') });
  await apply();
  const staticResult = await bundle('bottle-repaired.zip');
  assert.equal(staticResult.manifest.meshes.triangles, 106);
  const sourceZip = unzipSync(await readFile(join(dir, 'bottle.zip')));
  assert.deepEqual(staticResult.zip[staticResult.manifest.textures[0].file], sourceZip['bottle.fbm/BaseColor.png']);
  await click('repair-paint-new');
  assert.match(await text('paint-info'), /2 selected faces/);

  await open(join(dir, 'skinned-bottle.zip'), '2 bones');
  await enter('Bottle');
  await field('pick-B12').check();
  await select('repair-method', 'fan');
  await click('repair-preview');
  await report(/1 to fill · 2 skipped/);
  await apply();
  const skin = await bundle('skinned-bottle-repaired.zip');
  assert.equal(skin.manifest.meshes.triangles, 107);
  assert.equal(skin.manifest.meshes.clips, 1);
  assert.deepEqual(await contours(), ['B20', 'B48']);
  await download('save-project', 'skinned-repair.assetfixer');
  await open(join(dir, 'skinned-repair.assetfixer'), 'Project restored');
  await enter('Bottle');
  assert.deepEqual(await contours(), ['B20', 'B48']);

  assert.deepEqual(errors, []);
  assert.deepEqual(external, []);
  const result = { chrome: browser.version(), autoFilled: 2, protectedMouthEdges: 12, concavePlanar: 6, adjustedFan: 8,
    staticFbxTriangles: 106, skinnedFbxTriangles: 107, offlineRequests: external };
  await writeFile(join(dir, 'browser-report.json'), JSON.stringify(result, null, 2));
  console.log(JSON.stringify(result, null, 2));
} finally {
  await browser?.close();
  await new Promise(resolve => server.httpServer.close(resolve));
}
